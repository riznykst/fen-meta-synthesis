// Node tests for the static User Wiki & FAQ page (web/portal/faq.html).
// The page is plain HTML with <details> elements; these tests pin the
// sections and the honesty-critical explanations so they cannot quietly
// disappear in an edit.
"use strict";
const { test } = require("node:test");
const assert = require("node:assert");
const fs = require("node:fs");
const path = require("node:path");

const html = fs.readFileSync(path.join(__dirname, "..", "portal", "faq.html"), "utf-8");

test("faq has all wiki sections with anchors", () => {
  for (const id of [
    "start", "workflow", "verdicts", "statuses", "quotes", "contradictions",
    "dictionary", "provenance", "candidates", "errors", "data", "glossary", "limits",
  ]) {
    assert.match(html, new RegExp('id="' + id + '"'), "missing section " + id);
    assert.match(html, new RegExp('href="#' + id + '"'), "missing toc link " + id);
  }
});

test("faq explains every verdict button and the 409 accept lock", () => {
  for (const term of ["Accept", "Reject", "Dispute", "409", "Accept is disabled"]) {
    assert.ok(html.includes(term), "missing " + term);
  }
  assert.match(html, /Decided proposals/);
  assert.match(html, /immutable and\s+append-only/);
});

test("faq keeps the honesty boundaries explicit", () => {
  assert.match(html, /not<\/b> prove the claim is true/);
  assert.match(html, /model only proposes/);
  assert.match(html, /CC BY-SA 3\.0/);
  assert.match(html, /never generated by the agent/);
  assert.match(html, /must\s+never be exportable/);
});

test("faq maps classic voting buttons to verdicts and explains QV", () => {
  assert.match(html, /validated/);
  assert.match(html, /Quadratic Voting \(QV\)/);
  assert.match(html, /Details — what am I voting on\?/);
});

test("faq contains no script tags (static, zero-build)", () => {
  assert.ok(!/<script/i.test(html));
});

test("faq documents the three datasets and the EU AI Act walkthrough", () => {
  assert.match(html, /id="datasets"/);
  assert.match(html, /href="#datasets"/);
  for (const term of [
    "EU AI Act",
    "public texts",
    "Not legal",
    "SYNTHETIC source",
    "Article 18",
    "Article 11",
    "10 years",
    "model-found item",
    "gold_contradictions",
  ]) {
    assert.ok(html.includes(term), "missing " + term);
  }
  assert.match(html, /Walkthrough: the wrong-attribution case/);
  assert.match(html, /support uncertain/);
  assert.match(html, /location and meaning are\s+different things/);
});

test("faq explains the durable registry and what stays private", () => {
  assert.match(html, /registry_public/);
  assert.match(html, /publishable key/);
  assert.match(html, /401/);
  assert.match(html, /SELECT<\/code> on that one view/);
  assert.match(html, /refuses\s+<code>UPDATE<\/code> and <code>DELETE<\/code>/);
});
